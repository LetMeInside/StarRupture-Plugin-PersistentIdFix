#pragma once

// Defines the Client and legacy Server versions shared by PluginInfo, DLL
// resources, and CI. The build target selects the active version aliases.

#define CLIENT_VERSION_MAJOR 1
#define CLIENT_VERSION_MINOR 4
#define CLIENT_VERSION_PATCH 0

#define SERVER_VERSION_MAJOR 1
#define SERVER_VERSION_MINOR 3
#define SERVER_VERSION_PATCH 1

#if defined(MODLOADER_CLIENT_BUILD)
#define VERSION_MAJOR CLIENT_VERSION_MAJOR
#define VERSION_MINOR CLIENT_VERSION_MINOR
#define VERSION_PATCH CLIENT_VERSION_PATCH
#else
#define VERSION_MAJOR SERVER_VERSION_MAJOR
#define VERSION_MINOR SERVER_VERSION_MINOR
#define VERSION_PATCH SERVER_VERSION_PATCH
#endif

#define RESOURCE_VERSION_STRINGIFY_INNER(value) #value
#define RESOURCE_VERSION_STRINGIFY(value) \
    RESOURCE_VERSION_STRINGIFY_INNER(value)
#define PERSISTENTIDFIX_VERSION_STRING \
    RESOURCE_VERSION_STRINGIFY(VERSION_MAJOR) "." \
    RESOURCE_VERSION_STRINGIFY(VERSION_MINOR) "." \
    RESOURCE_VERSION_STRINGIFY(VERSION_PATCH)
#define RESOURCE_VERSION_STRING PERSISTENTIDFIX_VERSION_STRING ".0"
